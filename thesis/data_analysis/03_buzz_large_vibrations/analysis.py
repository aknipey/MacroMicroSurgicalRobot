#!/usr/bin/env python3
"""03 The high-frequency buzz: where (pose), in which output modes, and whether the command contains it.

Every real-arm bag from V5 on: /joint_states effort (motor current, A) per joint, 0.25 s Hann windows, 50 % overlap;
buzz = rms of the 80-249 Hz band-passed current (below the 250 Hz Nyquist of 500 Hz joint states) summed over the
three large joints (shoulder pan/lift, elbow). Each window carries its mean joint configuration, joint speed, output
mode and the 80-249 Hz content of the joint-velocity command (velocity / position output). Moving = joint speed
norm > 0.02 rad/s. Same-input comparison: V9b/NoTool LargeVibrations (position vs trajectory). Writes figures/ and RESULTS.md.
"""
import os
import sys

import numpy as np
from scipy.signal import butter, sosfiltfilt, spectrogram

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from common import bags, runs  # noqa: E402
from common.style import FULL, HALF, INK2, MODE, MUTED, SEQ, save, style  # noqa: E402
import matplotlib.pyplot as plt  # noqa: E402

FS = 500.0
SOS = butter(4, [80, 249], 'bandpass', fs=FS, output='sos')
BIG = [0, 1, 2]
W = int(0.25 * FS)
PATTERNS = ['V5/*', 'V7/*', 'V8/CalibratedKinematics/*', 'V9/*/*', 'V9b/*/*', 'V9b/NoTool/*/*']


def windows(run):
    b = bags.load(run, ['/joint_states', '/joint_velocity_limiter/commands', '/forward_velocity_controller/commands'])
    js = b.get('/joint_states')
    if js is None or len(js['th']) < 4 * W:
        return []
    cur = sosfiltfilt(SOS, js['current'], axis=0)
    cmd = b.get('/forward_velocity_controller/commands') or b.get('/joint_velocity_limiter/commands')
    chf = None
    if cmd is not None and len(cmd['tr']) > 4 * W and run.mode != 'trajectory':
        g = np.interp(js['tr'], cmd['tr'], np.arange(len(cmd['tr'])))       # command resampled on the joint clock
        c = np.column_stack([np.interp(js['tr'], cmd['tr'], cmd['data'][:, k]) for k in range(6)])
        chf = sosfiltfilt(SOS, c, axis=0)
    out = []
    for s in range(0, len(js['th']) - W, W // 2):
        sl = slice(s, s + W)
        out.append(dict(buzz=float(np.sqrt(np.mean(np.sum(cur[sl, BIG] ** 2, 1)))),
                        q=js['q'][sl].mean(0), speed=float(np.linalg.norm(js['qd'][sl].mean(0))),
                        cmd=float(np.sqrt(np.mean(np.sum(chf[sl] ** 2, 1)))) if chf is not None else np.nan,
                        t=float(js['tr'][s] - js['tr'][0]), mode=run.mode, run=run.key, traj=run.trajectory))
    return out


def main():
    style()
    seen, W_ = set(), []
    for pat in PATTERNS:
        for r in runs.find_runs(pat):
            if r.key in seen or not r.has('rosbag'):
                continue
            seen.add(r.key)
            W_ += windows(r)
    buzz = np.array([w['buzz'] for w in W_]); mv = np.array([w['speed'] > 0.02 for w in W_])
    modes = sorted({w['mode'] for w in W_})
    L = ['# 03 Results: high-frequency buzz (80–249 Hz motor current, big three joints)', '',
         f'Generated by `analysis.py`. {len(W_)} windows of 0.25 s from {len(seen)} real-arm bags (V5–V9b). Units: '
         '/joint_states effort as published by the UR driver (motor current, A).', '',
         '## Buzz by output mode (moving windows)', '', '| Mode | windows | median (A) | p95 (A) | max (A) |', '|---|---|---|---|---|']
    for m in modes:
        v = np.array([w['buzz'] for w in W_ if w['mode'] == m and w['speed'] > 0.02])
        if len(v):
            L.append(f'| {m} | {len(v)} | {np.median(v):.3f} | {np.percentile(v, 95):.3f} | {v.max():.3f} |')
    still = buzz[~mv]
    L += ['', f'Floor (still windows, all modes): median {np.median(still):.3f} A, p95 {np.percentile(still, 95):.3f} A.']
    # same input, two modes
    pos = [w for w in W_ if w['run'].endswith('PositionMode/LargeVibrations_Replay1')]
    tra = [w for w in W_ if w['run'].endswith('TrajectoryMode/LargeVibrations_Replay1')]
    v7 = [w for w in W_ if w['run'] == 'V7/LargeVibrations']
    L += ['', '## Same input (V7 LargeVibrations recording, replayed on 11-06)', '', '| Run | mode | median (A) | p95 (A) | max (A) |',
          '|---|---|---|---|---|']
    for lab, v in (('V7/LargeVibrations (original, velocity)', v7), ('V9b position replay', pos), ('V9b trajectory replay', tra)):
        b = np.array([w['buzz'] for w in v if w['speed'] > 0.02])
        if len(b):
            L.append(f'| {lab} | {v[0]["mode"]} | {np.median(b):.3f} | {np.percentile(b, 95):.3f} | {b.max():.3f} |')
    # pose dependence: which two joints separate high-buzz windows from the rest (velocity/position modes)
    vv = [w for w in W_ if w['mode'] != 'trajectory' and w['speed'] > 0.02]
    bq = np.array([w['buzz'] for w in vv]); Q = np.array([w['q'] for w in vv])
    hi = bq > np.percentile(bq, 95)
    sep = np.abs(Q[hi].mean(0) - Q[~hi].mean(0)) / Q.std(0)
    ja, jb = np.argsort(-sep)[:2]
    L += ['', '## Pose dependence (velocity and position output, moving windows)', '',
          f'Joints that best separate the top-5 % buzz windows from the rest (standardised mean difference): '
          + ', '.join(f'{runs.JOINTS[j]} {sep[j]:.2f}' for j in np.argsort(-sep)[:4]) + '.']
    cm = np.array([w['cmd'] for w in vv]); ok = np.isfinite(cm)
    if ok.sum() > 10:
        rho = np.corrcoef(np.argsort(np.argsort(cm[ok])), np.argsort(np.argsort(bq[ok])))[0, 1]
        L.append(f'Rank correlation of buzz with the 80–249 Hz content of the joint-velocity command: {rho:.2f} '
                 f'(n = {ok.sum()} windows). Low = the arm/drive produces the buzz without it being in the command.')
    L += ['', 'Limit: /joint_states at 500 Hz cannot see above 250 Hz; anything higher aliases into this band.', '',
          '## Prior claims checked', '', '- "speedj-only and pose-dependent"; "V9b position 0.32–0.35 A vs trajectory 0.055 A '
          'in 80–249 Hz": see the tables (different window definition: 0.25 s windows, big three joints, moving only).', '',
          '## Figures', '']
    fig, ax = plt.subplots(figsize=(FULL * 0.7, 3.0))
    o = np.argsort(bq)
    sc = ax.scatter(np.degrees(Q[o, ja]), np.degrees(Q[o, jb]), c=bq[o], s=3, cmap=SEQ, vmax=np.percentile(bq, 99))
    for lab, v, c in (('LargeVibrations', pos, '#D55E00'), ('NoBuzzArea', [w for w in W_ if w['run'].endswith('PositionMode/NoBuzzArea_Replay1')], 'white')):
        if v:
            qq = np.array([w['q'] for w in v])
            ax.plot(np.degrees(qq[:, ja]), np.degrees(qq[:, jb]), color=c, lw=0.8, label=lab)
    fig.colorbar(sc, ax=ax, label='80–249 Hz current (A)')
    ax.set_xlabel(f'{runs.JOINTS[ja]} (°)'); ax.set_ylabel(f'{runs.JOINTS[jb]} (°)'); ax.legend(fontsize=6.5)
    ax.set_title('Where the arm buzzes (velocity/position output, every bag)', fontsize=7.5)
    L.append(f"- `figures/{os.path.basename(save(fig, HERE, 'buzz_pose_map'))}`")
    # spectrogram pair
    fig, axes = plt.subplots(2, 1, figsize=(FULL, 3.4), sharex=True)
    vmax = None
    for ax, key, lab in zip(axes, ('PositionMode', 'TrajectoryMode'), ('position', 'trajectory')):
        r = runs.Run(os.path.join(runs.LOGS, 'V9b', 'NoTool', key, 'LargeVibrations_Replay1'))
        js = bags.load(r, ['/joint_states'])['/joint_states']
        f, t, S = spectrogram(js['current'][:, 1], fs=FS, nperseg=256, noverlap=192)
        S = 10 * np.log10(S + 1e-12)
        vmax = vmax or np.percentile(S, 99.5)
        im = ax.pcolormesh(t, f, S, shading='auto', vmin=vmax - 60, vmax=vmax, cmap=SEQ)
        ax.set_ylabel(f'{lab}\nHz'); ax.axhline(80, color='white', lw=0.5, ls='--')
    axes[-1].set_xlabel('time in bag (s)'); axes[0].set_title('Same input, two output modes: shoulder-lift current spectrogram', fontsize=7.5)
    fig.colorbar(im, ax=axes, label='dB')
    L.append(f"- `figures/{os.path.basename(save(fig, HERE, 'same_input_spectrograms'))}`")
    if ok.sum() > 10:
        fig, ax = plt.subplots(figsize=(HALF * 1.3, 2.6))
        for m in modes:
            sel = np.array([w['mode'] == m for w in vv]) & ok
            if sel.any():
                ax.scatter(cm[sel], bq[sel], s=3, color=MODE.get(m, MODE['position'])['color'], label=MODE.get(m, {}).get('label', m), alpha=0.5)
        ax.set_xscale('log'); ax.set_yscale('log'); ax.set_xlabel('command 80–249 Hz (rad/s)'); ax.set_ylabel('current 80–249 Hz (A)')
        ax.legend(fontsize=6, markerscale=3)
        L.append(f"- `figures/{os.path.basename(save(fig, HERE, 'command_vs_current'))}`")
    open(os.path.join(HERE, 'RESULTS.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
