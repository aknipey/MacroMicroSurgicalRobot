#!/usr/bin/env python3
"""19 What the recorded inputs ask of the arm (Chapter 3, benchmark table).

For each recorded input, the teleop target (TOUCH_PATH.csv, tool0 in base_link, exists only while WHITE is held)
of one replay is summarised: recording and engaged time, strokes (target gaps < 0.1 s, >= 0.5 s long), tool0
target speed (median, p95, max; target resampled at 100 Hz per stroke, central difference), tool0 target angular
speed p95, and the extent of the target path per base axis. Every replay of an input plays the same stylus file,
so one replay per input is enough; the run used is printed. These are TARGET speeds at the flange (tool0), not at
a tool tip. Writes RESULTS.md.

    cd thesis/data_analysis && python3 19_benchmark_inputs/analysis.py
"""
import os
import sys

import numpy as np
from scipy.spatial.transform import Rotation

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from common import runs  # noqa: E402

LOGS = os.path.join(runs.PKG, 'logs')
INPUTS = [  # (name, scale, run folder of one replay)
    ('LongBenchmark', '1:1', 'V9b/NoTool/PositionMode/LongBenchmark_Replay1'),
    ('ShortBenchmark', '1:1', 'V9b/NoTool/PositionMode/ShortBenchmark_Replay1'),
    ('NoBuzzArea', '1:1', 'V9b/NoTool/PositionMode/NoBuzzArea_Replay1'),
    ('LargeVibrations', '1:1', 'V9b/NoTool/PositionMode/LargeVibrations_Replay1'),
    ('Scaled5_Fast', '1:5', 'V9b/NoTool/PositionMode/Scaled5_Fast_Replay1'),
    ('Scaled5_Slow', '1:5', 'V9b/NoTool/PositionMode/Scaled5_Slow_Replay1'),
    ('RCMOnly', '1:5', 'V9/PositionMode/RCMOnlySimpleHolder_Replay1'),
    ('WholeRun', '1:1', 'V9/PositionMode/WholeRunDrinkBottleSimpleHolder_Replay1'),
    ('FastChecking', '1:1', 'V9/PositionMode/FastCheckingRCMSimpleHolder_Replay1'),
    ('SlowChecking', '1:1', 'V9/PositionMode/SlowCheckingRCMSimpleHolder_Replay1'),
    ('SingularityInput', '1:1', 'V9b/Singularity/GuardOn/SingularityInput_Replay1'),
]


def summarise(run):
    d = runs.read_csv(os.path.join(LOGS, run, 'TOUCH_PATH.csv'))
    t = np.asarray(d['t'], float)
    P = np.c_[d['x'], d['y'], d['z']] * 1e3
    Q = np.c_[d['qx'], d['qy'], d['qz'], d['qw']]
    segs = np.split(np.arange(len(t)), np.where(np.diff(t) > 0.1)[0] + 1)
    v, w, eng, n = [], [], 0.0, 0
    for s in segs:
        ts = t[s]
        if len(s) < 20 or ts[-1] - ts[0] < 0.5:
            continue
        n += 1
        eng += ts[-1] - ts[0]
        g = np.arange(ts[0], ts[-1], 0.01)
        Pg = np.column_stack([np.interp(g, ts, P[s, k]) for k in range(3)])
        v.append(np.linalg.norm(np.gradient(Pg, g, axis=0), axis=1))
        idx = np.clip(np.searchsorted(ts, g), 0, len(ts) - 1)
        R = Rotation.from_quat(Q[s][idx])
        w.append(np.degrees((R[1:] * R[:-1].inv()).magnitude() / 0.01))
    v, w = np.concatenate(v), np.concatenate(w)
    return dict(rec=t[-1] - t[0], eng=eng, strokes=n, v50=np.median(v), v95=np.percentile(v, 95), vmax=v.max(),
                w95=np.percentile(w, 95), ext=P.max(0) - P.min(0))


def main():
    L = ['# 19 Results: what the recorded inputs ask of the arm', '',
         'Generated by `analysis.py`. Teleop TARGET for tool0 (TOUCH_PATH.csv) of one replay per input; '
         'speeds at the flange, not at a tool tip. Strokes = target gaps < 0.1 s, >= 0.5 s long; speeds on a 100 Hz '
         'grid per stroke.', '',
         '| Input | scale | run used | recorded (s) | engaged (s) | strokes | speed median / p95 / max (mm/s) '
         '| angular speed p95 (°/s) | extent x, y, z (mm) |',
         '|---|---|---|---|---|---|---|---|---|']
    for name, scale, run in INPUTS:
        r = summarise(run)
        L.append(f"| {name} | {scale} | `{run}` | {r['rec']:.1f} | {r['eng']:.1f} | {r['strokes']} | "
                 f"{r['v50']:.0f} / {r['v95']:.0f} / {r['vmax']:.0f} | {r['w95']:.0f} | "
                 f"{r['ext'][0]:.0f}, {r['ext'][1]:.0f}, {r['ext'][2]:.0f} |")
    L += ['', 'Reference (not computed here): mean laparoscopic instrument-tip speeds of 24–39 mm/s in four FLS-type '
          'box-trainer tasks (von Bechtolsheim et al. 2023, Updates Surg 75:1103, Table 4).']
    open(os.path.join(HERE, 'RESULTS.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
