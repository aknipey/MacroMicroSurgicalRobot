#!/usr/bin/env python3
"""11 Pose-offset test: is the NDI-vs-robot disagreement between the SlowChecking latch pose and working pose a
property of the camera placement (measurement chain) or of the pose (arm / seat)?

Runs: logs/V9b/PoseOffset_Camera{1,2} (+ the FAILED/INCOMPLETE folders, which must fail the motion check).
Holds: joint speed < 0.002 rad/s for >= 2 s, labelled A/B by 2-means on the joint vector, 0.5 s trimmed.
Only frame-independent quantities are compared, so the two camera frames never need registering:
  tip distance |tip_A - tip_B|, shaft angle change angle(axis_A, axis_B), full rotation angle of A->B,
each from the robot (FK of /joint_states, calibrated kinematics, tool from META) and from the NDI (medians in the hold).
NDI and bag are matched on host time (NDI unix_time vs bag receive time).
"""
import glob
import os
import sys

import numpy as np
from scipy.spatial.transform import Rotation

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from common import bags, kin, ndi, runs  # noqa: E402
from common.style import FULL, HALF, INK2, save, style  # noqa: E402
import matplotlib.pyplot as plt  # noqa: E402

RNG = np.random.default_rng(11)
CAM = {'PoseOffset_Camera1': '#0072B2', 'PoseOffset_Camera2': '#E69F00'}


def holds(run):
    b = bags.load(run, ['/joint_states'])
    js = b.get('/joint_states')
    if js is None:
        return None, 'no /joint_states'
    sp = np.linalg.norm(js['qd'], axis=1)
    still = sp < 0.002
    out, i = [], 0
    while i < len(still):
        if still[i]:
            j = i
            while j < len(still) and still[j]:
                j += 1
            if js['tr'][j - 1] - js['tr'][i] >= 2.0:
                out.append((js['tr'][i] + 0.5, js['tr'][j - 1] - 0.5, np.median(js['q'][i:j], 0)))
            i = j
        else:
            i += 1
    return out, None


def analyse(run):
    hs, why = holds(run)
    if not hs or len(hs) < 4:
        return None, why or f'only {len(hs or [])} holds (motion not completed)'
    Qh = np.array([h[2] for h in hs])
    # 2-means on joints
    c = [Qh[0], Qh[np.argmax(np.linalg.norm(Qh - Qh[0], axis=1))]]
    for _ in range(10):
        lab = np.array([np.argmin([np.linalg.norm(q - ci) for ci in c]) for q in Qh])
        c = [Qh[lab == k].mean(0) for k in (0, 1)]
    if np.linalg.norm(c[0] - c[1]) < 0.05:
        return None, 'no second pose found'
    tool = (run.meta.get('tool') or {}).get('at_start') or {}
    tip_t, dir_t = np.array(tool['tip_tool0_mm']) / 1000, np.array(tool['direction_tool0'])
    K = kin.load(run.kinematics[1] or 'calibrated')
    n = ndi.load(run)
    vis = n['visible'] == 1
    rows = []
    for (a, b, q), l in zip(hs, lab):
        m = vis & (n['unix_time'] >= a) & (n['unix_time'] <= b)
        if m.sum() < 30:
            continue
        T = kin.tool0(K, q)
        rows.append(dict(lab=int(l), t=a,
                         tip_r=(T[:3, :3] @ tip_t + T[:3, 3]) * 1000, ax_r=T[:3, :3] @ dir_t, R_r=Rotation.from_matrix(T[:3, :3]),
                         tip_n=np.median(np.c_[n['tip_x'], n['tip_y'], n['tip_z']][m], 0),
                         ax_n=np.median(np.c_[n['axis_x'], n['axis_y'], n['axis_z']][m], 0),
                         R_n=Rotation.from_quat(np.median(np.c_[n['qx'], n['qy'], n['qz'], n['q0']][m], 0)),
                         sd_n=np.std(np.c_[n['tip_x'], n['tip_y'], n['tip_z']][m], 0)))
    cyc = []
    for i in range(len(rows) - 1):
        A, B = rows[i], rows[i + 1]
        if A['lab'] == B['lab']:
            continue
        ang = lambda u, v: np.degrees(np.arccos(np.clip(u @ v / np.linalg.norm(u) / np.linalg.norm(v), -1, 1)))
        cyc.append(dict(tip_r=np.linalg.norm(A['tip_r'] - B['tip_r']), tip_n=np.linalg.norm(A['tip_n'] - B['tip_n']),
                        ax_r=ang(A['ax_r'], B['ax_r']), ax_n=ang(A['ax_n'], B['ax_n']),
                        rot_r=np.degrees((A['R_r'].inv() * B['R_r']).magnitude()),
                        rot_n=np.degrees((A['R_n'].inv() * B['R_n']).magnitude())))
    return dict(run=run, holds=len(rows), cycles=cyc, hold_sd=np.median([r['sd_n'] for r in rows], 0)), None


def main():
    style()
    res, bad = [], []
    for d in sorted(glob.glob(os.path.join(runs.LOGS, 'V9b', 'PoseOffset_Camera*'))):
        r = runs.Run(d)
        a, why = analyse(r) if r.has('NDI_PATH.csv') else (None, 'no NDI_PATH.csv')
        (res.append(a) if a else bad.append((r.key, why)))
    L = ['# 11 Results: pose-offset test, two camera placements', '',
         'Generated by `analysis.py`. Frame-independent comparisons of the move between the two poses (A ↔ B), robot '
         '(FK, calibrated kinematics, META tool) vs NDI. A camera effect = the robot–NDI disagreement changes between '
         'placements.', '', '**Not usable (found by the motion check):**', '']
    L += [f'- `{k}`: {w}' for k, w in bad] or ['- none']
    L += ['', '| Run | holds | moves | tip distance robot / NDI (mm) | Δ tip (mm) | shaft angle robot / NDI (°) | Δ shaft (°) | '
          'rotation robot / NDI (°) | Δ rotation (°) |', '|---|---|---|---|---|---|---|---|---|']
    summ = {}
    for a in res:
        c = a['cycles']
        g = lambda k: np.array([x[k] for x in c])
        dtip, dax, drot = g('tip_n') - g('tip_r'), g('ax_n') - g('ax_r'), g('rot_n') - g('rot_r')
        summ[a['run'].name] = (dtip, dax, drot)
        L.append(f"| {a['run'].key} | {a['holds']} | {len(c)} | {g('tip_r').mean():.2f} / {g('tip_n').mean():.2f} | "
                 f"{dtip.mean():+.3f} ± {dtip.std(ddof=1):.3f} | {g('ax_r').mean():.3f} / {g('ax_n').mean():.3f} | "
                 f"{dax.mean():+.4f} ± {dax.std(ddof=1):.4f} | {g('rot_r').mean():.3f} / {g('rot_n').mean():.3f} | "
                 f"{drot.mean():+.4f} ± {drot.std(ddof=1):.4f} |")
    if len(summ) == 2:
        (k1, v1), (k2, v2) = summ.items()
        L += ['', '## Camera effect (Camera 2 − Camera 1), bootstrap 95 % CI over moves', '']
        for i, lab, unit in ((0, 'tip distance disagreement', 'mm'), (1, 'shaft-angle disagreement', '°'),
                             (2, 'rotation-angle disagreement', '°')):
            bs = [RNG.choice(v2[i], len(v2[i])).mean() - RNG.choice(v1[i], len(v1[i])).mean() for _ in range(5000)]
            lo, hi = np.percentile(bs, [2.5, 97.5])
            L.append(f'- {lab}: {v2[i].mean() - v1[i].mean():+.4f} {unit} [{lo:+.4f}, {hi:+.4f}]'
                     + (' → camera placement changes it' if lo > 0 or hi < 0 else ' → no detectable camera effect'))
        lever = 100.0
        L += ['', f'A shaft-angle disagreement of x° displaces the shaft line by about x·π/180·{lever:.0f} mm at '
              f'{lever:.0f} mm from where it is fixed, the scale of the RCM errors in folder 09.']
    L += ['', '## Prior claims checked', '', '- "tip distance 76.32 mm (robot) vs 76.46 / 76.47 mm (NDI); axis not yet '
          'analysed": see the table.', '', '## Figures', '']
    fig, axes = plt.subplots(1, 3, figsize=(FULL, 2.1))
    for ax, i, lab in zip(axes, range(3), ('tip distance: NDI − robot (mm)', 'shaft angle: NDI − robot (°)',
                                            'rotation: NDI − robot (°)')):
        for j, (k, v) in enumerate(summ.items()):
            x = np.full(len(v[i]), j) + RNG.uniform(-0.08, 0.08, len(v[i]))
            ax.scatter(x, v[i], s=14, color=CAM.get(k, INK2))
            ax.errorbar(j + 0.25, v[i].mean(), yerr=1.96 * v[i].std(ddof=1) / np.sqrt(len(v[i])), fmt='o',
                        color='k', ms=3, capsize=2)
        ax.axhline(0, color=INK2, lw=0.6)
        ax.set_xticks(range(len(summ))); ax.set_xticklabels([k.replace('PoseOffset_', '') for k in summ])
        ax.set_title(lab, fontsize=7)
    L.append(f"- `figures/{os.path.basename(save(fig, HERE, 'camera_effect'))}`")
    open(os.path.join(HERE, 'RESULTS.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
