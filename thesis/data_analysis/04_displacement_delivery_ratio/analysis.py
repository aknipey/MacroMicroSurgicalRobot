#!/usr/bin/env python3
"""04 Displacement delivery: what fraction of MoveIt Servo's commanded displacement the arm covers, per output mode.

Commanded = /servo_node/delta_twist_cmds (the twist the teleop sends Servo), integrated. Delivered = tool0 from FK
of /joint_states (the run's kinematics; nominal UR16e when META has none), projected on the commanded direction
after shifting by the best velocity lag (so lag does not count as shortfall). Per stroke (|commanded linear speed|
> 2 mm/s for >= 0.5 s): Theil-Sen slope of cumulative delivered vs cumulative commanded path. A run is excluded
if META's tcp_offset.check_max_mm > 5 mm (TF used the wrong arm's kinematics). Writes figures/ and RESULTS.md.
"""
import os
import sys

import numpy as np
from scipy.stats import theilslopes

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from common import bags, kin, runs  # noqa: E402
from common.style import FULL, HALF, INK2, MODE, MUTED, save, style  # noqa: E402
import matplotlib.pyplot as plt  # noqa: E402

DT = 0.01
PATTERNS = ['V1/V1_*', 'V2/*', 'V3/*', 'V5/*', 'V9b/NoTool/*/*_Replay1', 'SIM_latency/*']


def analyse(run):
    b = bags.load(run, ['/joint_states', '/servo_node/delta_twist_cmds'])
    if '/servo_node/delta_twist_cmds' not in b or '/joint_states' not in b:
        return None
    tw, js = b['/servo_node/delta_twist_cmds'], b['/joint_states']
    K = kin.load(run.kinematics[1] or 'nominal')
    g = np.arange(max(tw['th'][0], js['th'][0]), min(tw['th'][-1], js['th'][-1]), DT)
    if len(g) < 200:
        return None
    v_cmd = np.column_stack([np.interp(g, tw['th'], tw['lin'][:, k]) for k in range(3)]) * 1000      # mm/s
    Q = np.column_stack([np.interp(g, js['th'], js['q'][:, k]) for k in range(6)])
    P = np.array([kin.tool0(K, q)[:3, 3] for q in Q]) * 1000
    v_arm = np.gradient(P, DT, axis=0)
    # best lag (velocity correlation), 0-1.5 s
    best = (-np.inf, 0)
    for s in range(0, 150):
        a, c = v_cmd[: len(g) - s], v_arm[s:]
        r = np.sum(a * c) / np.sqrt(np.sum(a * a) * np.sum(c * c))
        best = max(best, (r, s))
    lag = best[1]
    vc, va = v_cmd[: len(g) - lag], v_arm[lag:]
    sp = np.linalg.norm(vc, axis=1)
    mv = sp > 2.0
    slopes, strokes = [], []
    i = 0
    while i < len(mv):
        if mv[i]:
            j = i
            while j < len(mv) and mv[j]:
                j += 1
            if (j - i) * DT >= 0.5:
                u = vc[i:j] / sp[i:j, None]
                s_cmd = np.cumsum(sp[i:j]) * DT
                s_dlv = np.cumsum(np.sum(va[i:j] * u, 1)) * DT
                slopes.append(theilslopes(s_dlv, s_cmd)[0])
                strokes.append((s_cmd, s_dlv, float(np.median(sp[i:j]))))
            i = j
        else:
            i += 1
    if not slopes:
        return None
    w = np.array([s[0][-1] for s in strokes])
    return dict(run=run, lag_ms=lag * DT * 1e3, frame=str(tw['frame']), slopes=np.array(slopes), weights=w,
                ratio=float(np.average(slopes, weights=w)), strokes=strokes,
                total=float(sum(s[1][-1] for s in strokes) / sum(s[0][-1] for s in strokes)))


def main():
    style()
    out, excluded = [], []
    for pat in PATTERNS:
        for r in runs.find_runs(pat):
            # No exclusion on META tcp_offset.check_max_mm: it mostly measures TF timing while moving
            # (scripts/kinematics_check.py), and this analysis uses FK of the joints, not TF.
            try:
                a = analyse(r)
            except Exception as e:                       # report, do not hide
                excluded.append((r.key, f'error: {e!r}'))
                continue
            if a and a['total'] < 0.02:
                excluded.append((r.key, f"arm did not follow: delivered {100 * a['total']:.1f} % of the commanded path "
                                        f"(lookahead setting: {[f'{k}={v}' for k, v in r.settings.items() if 'LOOKAHEAD' in k]})"))
                continue
            if a:
                a['sim'] = r.key.startswith('SIM')
                out.append(a)
                print(r.key, r.mode, f"ratio {a['ratio']:.2f} lag {a['lag_ms']:.0f} ms, {len(a['slopes'])} strokes")
    modes = sorted({(o['run'].mode, o['sim']) for o in out})
    L = ['# 04 Results: displacement delivery ratio', '', 'Generated by `analysis.py`. Ratio = Theil–Sen slope of '
         'delivered (FK of /joint_states, along the commanded direction, lag removed) vs commanded (integrated '
         '/servo_node/delta_twist_cmds) path per stroke, path-weighted over strokes. Twist frames seen: '
         + ', '.join(sorted({o['frame'] for o in out})) + '.', '', '**Excluded:**', '']
    L += [f'- `{k}`: {why}' for k, why in excluded] or ['- none']
    L += ['', '## Per mode', '', '| Mode | real / emulator | runs | ratio: median [range] | lag (ms) |', '|---|---|---|---|---|']
    for m, sim in modes:
        v = [o for o in out if o['run'].mode == m and o['sim'] == sim]
        rr = [o['ratio'] for o in v]
        L.append(f"| {m} | {'emulator' if sim else 'real arm'} | {len(v)} | {np.median(rr):.2f} [{min(rr):.2f}–{max(rr):.2f}] | "
                 f"{np.median([o['lag_ms'] for o in v]):.0f} |")
    L += ['', '## Per run', '', '| Run | mode | lookahead / notes | ratio | strokes | lag (ms) |', '|---|---|---|---|---|---|']
    for o in out:
        s = o['run'].settings
        note = ', '.join(f'{k}={s[k]}' for k in s if 'LOOKAHEAD' in k)
        L.append(f"| {o['run'].key} | {o['run'].mode} | {note} | {o['ratio']:.2f} | {len(o['slopes'])} | {o['lag_ms']:.0f} |")
    L += ['', 'V1 (position output straight from Servo) lags beyond the 1.5 s search window on some strokes; its '
          'ratio is the crawl itself, so the lag column is not meaningful there.']
    L += ['', '## Prior claims checked', '', '- "trajectory 0.60, real and emulator, independent of lookahead; velocity 1.04; '
          'position not measured": see the tables.', '', '## Figures', '']

    fig, ax = plt.subplots(figsize=(FULL * 0.6, 2.8))
    for o in out:
        if o['sim']:
            continue
        st = MODE.get(o['run'].mode, MODE['position'])
        for s_cmd, s_dlv, _ in o['strokes']:
            ax.plot(s_cmd, s_dlv, color=st['color'], lw=0.5, alpha=0.5)
    lim = max(s[0][-1] for o in out if not o['sim'] for s in o['strokes'])
    med_traj = float(np.median([o['ratio'] for o in out if not o['sim'] and o['run'].mode == 'trajectory']))
    for k, ls in ((1.0, '-'), (med_traj, '--')):
        ax.plot([0, lim], [0, k * lim], color=INK2, lw=0.8, ls=ls)
        ax.text(lim, k * lim, f' {k:.2f}', fontsize=8, color=INK2, va='center')
    hs, seen = [], set()
    for m in sorted({o['run'].mode for o in out if not o['sim']}):
        if m in MODE and MODE[m]['label'] not in seen:
            seen.add(MODE[m]['label'])
            hs.append(plt.Line2D([], [], color=MODE[m]['color'], label=MODE[m]['label']))
    ax.legend(handles=hs, loc='upper left')
    ax.set_xlabel('Commanded displacement (mm)'); ax.set_ylabel('Delivered displacement (mm)')
    L.append(f"- `figures/{os.path.basename(save(fig, HERE, 'delivered_vs_commanded'))}`: every stroke, delivered vs "
             f"commanded path; solid = 1, dashed = the median trajectory-output ratio ({med_traj:.2f})")

    fig, ax = plt.subplots(figsize=(HALF * 1.4, 2.4))
    for m, sim in modes:
        st = MODE.get(m, MODE['position'])
        sp = np.concatenate([[s[2] for s in o['strokes']] for o in out if o['run'].mode == m and o['sim'] == sim])
        sl = np.concatenate([o['slopes'] for o in out if o['run'].mode == m and o['sim'] == sim])
        ax.scatter(sp, sl, s=10, marker=st['marker'], facecolor='none' if sim else st['color'], edgecolor=st['color'],
                   lw=0.6, label=f"{st['label']}{' (emulator)' if sim else ''}")
    ax.axhline(1.0, color=INK2, lw=0.7); ax.axhline(med_traj, color=INK2, lw=0.7, ls='--')
    ax.set_xscale('log'); ax.set_xlabel('Median commanded speed per stroke (mm/s)'); ax.set_ylabel('Delivery ratio')
    ax.legend(fontsize=7, ncol=2); ax.set_ylim(0, 1.6)
    L.append(f"- `figures/{os.path.basename(save(fig, HERE, 'ratio_vs_speed'))}`")
    open(os.path.join(HERE, 'RESULTS.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L[:30]))


if __name__ == '__main__':
    main()
