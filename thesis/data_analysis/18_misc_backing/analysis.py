#!/usr/bin/env python3
"""18 Small backing numbers: singularity amplification, the macro-micro demonstration, the micro-tool calibration.

1. Amplification near a singularity: along the real-arm guard-off stroke (V9b/Singularity/GuardOff, replay 1), the
   Jacobian of each /joint_states sample (calibrated kinematics); the largest joint speed per unit tool twist is
   1 / s_min(J). Reported relative to the stroke's start pose, at the samples where c crosses 30, 60, 100 and 200.
2. Demonstration counts from logs/V9b/MacroMicroDemo/micro_module_control.log: motor command messages ('Sending motor
   commands'), switches into MICRO and back, and the logged span.
3. Micro-tool calibration: the newest config/calibrations/micro_tool_*.json as written by
   scripts/calibration/micro_tool_calibration.py (tip, fit rms, dot rms, agreement of the two halves).
Writes RESULTS.md.
"""
import glob
import json
import os
import re
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from common import bags, kin, runs  # noqa: E402
from common.style import FULL, HALF, INK2, save, style  # noqa: E402
import matplotlib.pyplot as plt  # noqa: E402


def amplification():
    r = runs.Run(os.path.join(runs.LOGS, 'V9b/Singularity/GuardOff/SingularityInput_Replay1'))
    K = kin.load(r.kinematics[0] or 'calibrated')
    js = bags.load(r, ['/joint_states'])['/joint_states']
    q = js['q'][::10]
    sv = np.array([np.linalg.svd(kin.jacobian(K, x), compute_uv=False) for x in q])
    c = sv[:, 0] / sv[:, -1]
    amp = (1 / sv[:, -1]) / (1 / sv[0, -1])
    out = [('start', c[0], 1.0)]
    for thr in (30, 60, 100, 200):
        i = np.where(c >= thr)[0]
        if len(i):
            out.append((f'c ≥ {thr} (first)', c[i[0]], amp[i[0]]))
    return r.key, out, (c, amp)


def demo():
    p = os.path.join(runs.LOGS, 'V9b/MacroMicroDemo/micro_module_control.log')
    stamps, cmds, micro, macro = [], 0, 0, 0
    for line in open(p):
        m = re.search(r'\[(\d{10}\.\d+)\]', line)
        if m:
            stamps.append(float(m.group(1)))
        if 'Sending motor commands' in line:
            cmds += 1
        if 'Teleop mode MICRO' in line:
            micro += 1
        if 'Teleop mode MACRO' in line:
            macro += 1
    return dict(cmds=cmds, micro=micro, macro=macro, span=stamps[-1] - stamps[0])


def micro_cal():
    f = sorted(glob.glob(os.path.join(runs.PKG, 'config', 'calibrations', 'micro_tool_*.json')))[-1]
    return os.path.basename(f), json.load(open(f))


def main():
    style()
    key, amp, (cs, amps) = amplification()
    L = ['# 18 Results: small backing numbers', '', 'Generated by `analysis.py`.', '',
         f'## 1. Joint-speed amplification towards the wrist singularity ({key}, calibrated kinematics)', '',
         '| Pose | condition number c | largest joint speed per unit tool twist, relative to the start |', '|---|---|---|']
    L += [f'| {n} | {c:.1f} | {a:.1f}× |' for n, c, a in amp]
    d = demo()
    L += ['', '## 2. Macro–micro demonstration (logs/V9b/MacroMicroDemo)', '',
          f"- micro motor command messages: {d['cmds']}", f"- switches into MICRO: {d['micro']}; MACRO announcements "
          f"(incl. the start): {d['macro']}", f"- logged span: {d['span']:.0f} s"]
    name, cal = micro_cal()
    tip = np.array(cal['tip_tool0_mm'])
    L += ['', f'## 3. Micro-tool calibration ({name})', '',
          f"- tip in tool0: ({tip[0]:.2f}, {tip[1]:.2f}, {tip[2]:.2f}) mm, |tip| {np.linalg.norm(tip):.1f} mm, "
          f"extension {cal.get('extension_mm')} mm",
          f"- fit rms {cal['fit_rms_mm']:.2f} mm; per-dot rms {min(cal['dot_rms_mm']):.2f}–{max(cal['dot_rms_mm']):.2f} mm; "
          f"tip from the two halves of the data {cal['halves_tip_gap_mm']:.2f} mm apart; dot span {cal['dot_span_mm']:.0f} mm",
          '', '## Figures', '']
    fig, ax = plt.subplots(figsize=(FULL * 0.5, 2.3))
    ax.plot(cs, amps, '.', ms=2, color='#0072B2')
    for thr, lab in ((60, 'Guard stop'), (200, 'Servo halt')):
        ax.axvline(thr, color=INK2, lw=0.7, ls=':')
        ax.text(thr * 0.96, max(amps) * 0.97, lab, fontsize=8, color=INK2, ha='right', va='top')
    ax.set_xscale('log'); ax.set_xlabel('Condition number $c$')
    ax.set_ylabel('Joint speed per unit tool\nmotion (relative to start)')
    L += [f"- `figures/{os.path.basename(save(fig, HERE, 'singularity_amplification'))}`: largest joint speed per unit "
          "tool twist (1/s_min, relative to the start pose) against c along the guard-off stroke",
          '', '## Prior claims checked', '',
          '- "at c = 100 a joint moves ~50× faster than the tool suggests"; "983 micro motor commands and seven mode switches '
          'over 754 s"; "tip (−6.41, 15.56, 436.28) mm, 0.5–1 mm accuracy": see above.']
    open(os.path.join(HERE, 'RESULTS.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
