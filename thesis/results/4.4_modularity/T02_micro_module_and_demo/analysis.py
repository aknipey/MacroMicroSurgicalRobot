#!/usr/bin/env python3
"""T02 Micro module: the macro-micro demonstration and the micro-tool calibration (report 4.4.2).

1. Demonstration counts from V9b/MacroMicroDemo/micro_module_control.log: motor command messages ('Sending motor
   commands'), switches into MICRO and back, and the logged span.
2. Micro-tool calibration: the newest config/calibrations/micro_tool_*.json as written by
   scripts/calibration/micro_tool_calibration.py (tip, fit rms, dot rms, agreement of the two halves).
Writes RESULTS.md.
"""
import glob
import json
import os
import re
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(os.path.dirname(HERE)))  # thesis/results
from common import runs  # noqa: E402


def demo():
    p = os.path.join(runs.LOGS, 'V9b/MacroMicroDemo/micro_module_control.log')
    stamps, cmds, micro, macro = [], 0, 0, 0
    for line in open(p):
        m = re.search(r'\[(\d{10}\.\d+)\]', line)
        if m:
            stamps.append(float(m.group(1)))
        if 'Sending motor commands' in line:
            cmds += 1
        if 'Teleop mode MICRO' in line:
            micro += 1
        if 'Teleop mode MACRO' in line:
            macro += 1
    return dict(cmds=cmds, micro=micro, macro=macro, span=stamps[-1] - stamps[0])


def micro_cal():
    f = sorted(glob.glob(os.path.join(runs.PKG, 'config', 'calibrations', 'micro_tool_*.json')))[-1]
    return os.path.basename(f), json.load(open(f))


def main():
    d = demo()
    L = ['# T02 Results: macro–micro demonstration and micro-tool calibration', '', 'Generated by `analysis.py`.', '',
         '## 1. Macro–micro demonstration (V9b/MacroMicroDemo)', '',
         f"- micro motor command messages: {d['cmds']}", f"- switches into MICRO: {d['micro']}; MACRO announcements "
         f"(incl. the start): {d['macro']}", f"- logged span: {d['span']:.0f} s"]
    name, cal = micro_cal()
    tip = np.array(cal['tip_tool0_mm'])
    L += ['', f'## 2. Micro-tool calibration ({name})', '',
          f"- tip in tool0: ({tip[0]:.2f}, {tip[1]:.2f}, {tip[2]:.2f}) mm, |tip| {np.linalg.norm(tip):.1f} mm, "
          f"extension {cal.get('extension_mm')} mm",
          f"- fit rms {cal['fit_rms_mm']:.2f} mm; per-dot rms {min(cal['dot_rms_mm']):.2f}–{max(cal['dot_rms_mm']):.2f} mm; "
          f"tip from the two halves of the data {cal['halves_tip_gap_mm']:.2f} mm apart; dot span {cal['dot_span_mm']:.0f} mm",
          '', '## Prior claims checked', '',
          '- "983 micro motor commands and seven mode switches over 754 s"; "tip (−6.41, 15.56, 436.28) mm, '
          '0.5–1 mm accuracy": see above.']
    open(os.path.join(HERE, 'RESULTS.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
