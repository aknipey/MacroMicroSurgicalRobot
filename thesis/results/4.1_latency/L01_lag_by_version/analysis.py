#!/usr/bin/env python3
"""L01 Lag by version: one recorded input (V3 LongBenchmark) through every stack it was replayed on, plus V1/V2 moves.

Chain (REPLAY.yaml replay_of = V3/LongBenchmark, plus the original): metrics from common.track; faults found from
the data (the arm stops following - tool0 speed < 1 mm/s for 0.5 s while the target moves > 20 mm/s - before the
input ends); the label of each step = the META settings that changed from the previous stack (automatic diff).
V1/V2 moves are a separate panel (different inputs). Writes figures/ and RESULTS.md.
"""
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(os.path.dirname(HERE)))  # thesis/results
from common import runs, track  # noqa: E402
from common.style import FULL, INK2, MODE, MUTED, save, style  # noqa: E402
import matplotlib.pyplot as plt  # noqa: E402

KEYS = ('SERVO_OUTPUT', 'TOUCH_COMMAND_FILTER', 'TOUCH_KALMAN', 'TOUCH_PUBLISH_RATE', 'SERVO_SMOOTH_SPEEDJ',
        'SERVO_POSITION_LEAD', 'VELOCITY_LIMITER_SMOOTHING', 'TOUCH_POSITION_GAIN', 'TOUCH_FEEDFORWARD')


def chain_runs():
    out = []
    for r in runs.find_runs('*/*') + runs.find_runs('*/*/*') + runs.find_runs('*/*/*/*'):
        src = str(r.replay.get('replay_of', ''))
        if r.key == 'V3/LongBenchmark' or src.endswith('V3/LongBenchmark'):
            if 'NoTool' in r.key and r.replay_n != 1:
                continue
            out.append(r)
    order = lambda r: (r.date, r.key)
    return sorted(out, key=order)


def fault(run):
    p = track.load_paths(run)
    if p is None:
        return None
    (tt, tp, _), (ut, up, _) = p
    g = np.arange(max(tt[0], ut[0]), min(tt[-1], ut[-1]), 0.01)
    if len(g) < 100:
        return None
    vt = np.linalg.norm(np.gradient(np.column_stack([np.interp(g, tt, tp[:, k]) for k in range(3)]), 0.01, axis=0), axis=1)
    va = np.linalg.norm(np.gradient(np.column_stack([np.interp(g, ut, up[:, k]) for k in range(3)]), 0.01, axis=0), axis=1)
    stopped = (va < 1.0) & (vt > 20.0)
    run_len = np.convolve(stopped, np.ones(50), 'same')
    i = np.where(run_len >= 50)[0]
    return float(g[i[0]]) if len(i) else None


def settings_diff(a, b):
    sa, sb = a.settings, b.settings
    return ', '.join(f'{k} {sa.get(k)}→{sb.get(k)}' for k in KEYS if sa.get(k) != sb.get(k)) or 'no setting change'


def main():
    style()
    ch = chain_runs()
    rows = []
    for i, r in enumerate(ch):
        m = track.cached_metrics(r)
        f = fault(r)
        if f:                                   # metrics only up to the fault: after it the arm is not following
            (tt, tp, tq), (ut, up, uq) = track.load_paths(r)
            a, b = tt < f, ut < f
            m = track.metrics_arrays(tt[a], tp[a], tq[a], ut[b], up[b], uq[b])
        rows.append(dict(run=r, m=m, fault=f, diff=settings_diff(ch[i - 1], r) if i else 'original recording',
                         end=float(r.csv('TOUCH_PATH.csv')['t'][-1])))
    L = ['# L01 Results: lag by version, one input (V3 LongBenchmark) through every stack', '',
         'Generated by `analysis.py`. Lag = best position shift (common.track); "fault" = the arm stopped following '
         '(< 1 mm/s for 0.5 s while the target moved > 20 mm/s) before the input ended.', '',
         '| Stack (run) | date | mode | lag translation / rotation (ms) | lag-removed error (mm) | fault at (s) | change from previous |',
         '|---|---|---|---|---|---|---|']
    for o in rows:
        m = o['m'] or {}
        L.append(f"| {o['run'].key} | {o['run'].date} | {o['run'].mode} | {m.get('lag_ms', np.nan):.0f} / "
                 f"{m.get('lag_rot_ms', np.nan):.0f} | {m.get('err_mm', np.nan):.2f} | "
                 f"{'%.1f of %.1f' % (o['fault'], o['end']) if o['fault'] else '–'} | {o['diff']} |")
    # V1 / V2 panel
    v12 = [r for r in runs.find_runs('V1/V1_*') + runs.find_runs('V2/*')]
    L += ['', '## V1 (position straight from Servo) vs V2 (trajectory output): single moves', '',
          'Single step-and-hold moves make the position-shift estimator ill-posed (flat cost while the arm holds), so these '
          'use the velocity cross-correlation lag, and only the component the move exercises: translation for the 10 cm '
          'moves, rotation for the 90° moves, both for general motion. Search limit 1.6 s.', '',
          '| Run | mode | component | lag (ms) |', '|---|---|---|---|']
    v12rows = []
    for r in v12:
        m = track.cached_metrics(r)
        if not m:
            continue
        comp = 'rotation' if '90_Degrees' in r.name else ('translation' if '10CM' in r.name else 'both')
        if comp == 'rotation':
            val = f"{m['lag_rot_ms']:.0f}" + (' (≥ search limit)' if m['lag_rot_ms'] > 1590 else '')
        elif comp == 'translation':
            val = f"{m['lag_vel_ms']:.0f}" + (' (≥ search limit)' if m['lag_vel_ms'] > 1590 else '')
        else:
            val = f"{m['lag_vel_ms']:.0f} / {m['lag_rot_ms']:.0f}"
        v12rows.append((r, m))
        L.append(f"| {r.key} | {r.mode} | {comp} | {val} |")
    L += ['', '## Prior claims checked', '', '- "V1 640–760 ms translation, > 1.5 s rotation; V2 angle lag 128–158 ms; '
          'V5 62/58 ms; V9b 66–78 ms": see the tables.', '', '## Figures', '']

    # fig 1: same hand, every stack - 4 s excerpt where the target moves most
    ok = [o for o in rows if o['m']]
    (tt, tp, _), _ = track.load_paths(ok[0]['run'])
    k = int(np.argmax(np.ptp(tp, 0)))
    g = np.arange(tt[0], tt[-1], 0.01)
    sp = np.abs(np.gradient(np.interp(g, tt, tp[:, k]), 0.01))
    w = np.convolve(sp, np.ones(400), 'valid')
    t0 = g[int(np.argmax(w))]
    fig, axes = plt.subplots(len(ok), 1, figsize=(FULL, 0.62 * len(ok) + 0.5), sharex=True)
    for ax, o in zip(axes, ok):
        (tt, tp, _), (ut, up, _) = track.load_paths(o['run'])
        sel_t = (tt >= t0) & (tt <= t0 + 4); sel_u = (ut >= t0) & (ut <= t0 + 4)
        ax.plot(tt[sel_t] - t0, tp[sel_t, k], color='#C9C8C3', lw=2.2)
        ax.plot(ut[sel_u] - t0, up[sel_u, k], color=MODE.get(o['run'].mode, MODE['position'])['color'], lw=1.1)
        if o['fault'] and t0 <= o['fault'] <= t0 + 4:
            ax.plot(o['fault'] - t0, np.interp(o['fault'], ut, up[:, k]), 'x', color='k', ms=7)
        ax.set_yticks([])
        ax.text(4.05, np.mean(ax.get_ylim()), f"{o['run'].key.replace('/LongBenchmark', '').replace('_Replay1', '')}\n"
                f"{o['m']['lag_ms']:.0f} ms" + (' · faulted' if o['fault'] else ''), fontsize=6.3, va='center')
    axes[-1].set_xlabel('time (s); grey = operator target, colour = arm, one axis')
    axes[0].set_title('Same hand, every stack: V3 LongBenchmark replayed', fontsize=7.5)
    L.append(f"- `figures/{os.path.basename(save(fig, HERE, 'same_hand_every_stack'))}`")

    # fig 1b: compact version for the report, one stack per output route
    pick = [('V3/LongBenchmark1', 'V3 trajectory output'), ('V4/LongBenchmark_failed', 'V4 velocity output, first version'),
            ('V5/LongBenchmark', 'V5 velocity output, 500 Hz + limiter'),
            ('V9b/NoTool/PositionMode/LongBenchmark_Replay1', 'V9 position output (final)'),
            ('V9b/NoTool/TrajectoryMode/LongBenchmark_Replay1', 'V9 trajectory output, same day')]
    sel = [(next(o for o in ok if o['run'].key == k), lab) for k, lab in pick if any(o['run'].key == k for o in ok)]
    fig, axes = plt.subplots(len(sel), 1, figsize=(FULL, 0.72 * len(sel) + 0.7), sharex=True, sharey=True)
    for ax, (o, lab) in zip(axes, sel):
        (tt, tp, _), (ut, up, _) = track.load_paths(o['run'])
        sel_t = (tt >= t0) & (tt <= t0 + 4); sel_u = (ut >= t0) & (ut <= t0 + 4)
        ref = np.interp(t0, tt, tp[:, k])          # position relative to the target at the window start (track: mm)
        ax.plot(tt[sel_t] - t0, tp[sel_t, k] - ref, color='#C9C8C3', lw=2.2, label='Operator target')
        ax.plot(ut[sel_u] - t0, up[sel_u, k] - ref, color=MODE.get(o['run'].mode, MODE['position'])['color'],
                lw=1.1, label='Arm')
        if o['fault'] and t0 <= o['fault'] <= t0 + 4:
            ax.plot(o['fault'] - t0, np.interp(o['fault'], ut, up[:, k]) - ref, 'x', color='k', ms=7,
                    label='Fault')
        ax.text(0.01, 0.93, f"{lab}: {o['m']['lag_ms']:.0f} ms" + (', faulted' if o['fault'] else ''),
                transform=ax.transAxes, fontsize=8, va='top')
    axes[-1].set_xlabel('Time (s)')
    fig.supylabel('Position along the main axis (mm)', fontsize=9)
    hs = [plt.Line2D([], [], color='#C9C8C3', lw=2.2), plt.Line2D([], [], color=INK2, lw=1.1),
          plt.Line2D([], [], color='k', marker='x', ls='', ms=7)]
    axes[0].legend(hs, ['Operator target', 'Arm (colour = output route)', 'Fault'], ncol=3, loc='lower right',
                   bbox_to_anchor=(1.0, 1.0))
    L.append(f"- `figures/{os.path.basename(save(fig, HERE, 'same_hand_key_stacks'))}`: the same 4 s of V3/LongBenchmark "
             "through five stacks (compact version of the figure above)")

    # fig 2: lag ladder on a log axis
    fig, ax = plt.subplots(figsize=(FULL, 0.3 * (len(ok) + len(v12rows)) + 0.8))
    y = 0
    labels = []
    for r, m in v12rows + [(o['run'], o['m']) for o in ok]:
        st = MODE.get(r.mode, MODE['position'])
        ax.plot(m['lag_ms'], y, marker=st['marker'], color=st['color'], ms=6)
        ax.plot(m['lag_rot_ms'], y, marker=st['marker'], mfc='white', color=st['color'], ms=6)
        labels.append(r.key.replace('/LongBenchmark', ' LongBench.').replace('_Replay1', ''))
        y += 1
    ax.set_yticks(range(y)); ax.set_yticklabels(labels, fontsize=6)
    ax.invert_yaxis(); ax.set_xscale('log'); ax.axvline(50, color=INK2, ls='--', lw=0.7)
    ax.set_xlabel('lag (ms, log): filled = translation, hollow = rotation')
    L.append(f"- `figures/{os.path.basename(save(fig, HERE, 'lag_ladder'))}`")
    open(os.path.join(HERE, 'RESULTS.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
