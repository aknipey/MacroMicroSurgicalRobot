ON, OFF = '#0072B2', '#D55E00'


def cond_and_rate(K, q, twist):
    """c and dc/dt implied by the commanded twist (6,) at joint vector q."""
    J = kin.jacobian(K, q)
    c0 = np.linalg.cond(J)
    g = np.zeros(6)
    for i in range(6):
        dq = np.zeros(6); dq[i] = 1e-5
        g[i] = (np.linalg.cond(kin.jacobian(K, q + dq)) - np.linalg.cond(kin.jacobian(K, q - dq))) / 2e-5
    try:
        gx = np.linalg.solve(J.T, g)          # gradient of c w.r.t. the twist
    except np.linalg.LinAlgError:
        return c0, np.nan
    return c0, float(gx @ twist)


def analyse(run):
    b = bags.load(run, ['/joint_states', 'teleop/condition_number', '/servo_node/status',
                        '/servo_node/delta_twist_cmds'])
    K = kin.load(run.kinematics[1] or 'nominal')
    js = b['/joint_states']
    sel = np.arange(0, len(js['tr']), 25)                         # 20 Hz is plenty for c(t)
    tw = b.get('/servo_node/delta_twist_cmds')
    cs, rate = [], []
    for i in sel:
        tq = js['tr'][i]
        if tw is not None:
            k = np.searchsorted(tw['tr'], tq)
            k = min(max(k, 0), len(tw['tr']) - 1)
            twist = np.r_[tw['lin'][k], tw['ang'][k]] if abs(tw['tr'][k] - tq) < 0.05 else np.zeros(6)
        else:
            twist = np.zeros(6)
        c, r = cond_and_rate(K, js['q'][i], twist)
        cs.append(c); rate.append(r)
    off0 = bags.to_run_clock(run, bags.load(run))
    t0 = off0 if off0 is not None else js['tr'][0]
    ct = b.get('teleop/condition_number')
    st = b.get('/servo_node/status')
    ur = run.csv('UR_PATH.csv')
    P = np.c_[ur['x'], ur['y'], ur['z']] * 1000
    d = np.linalg.norm(P - P[0], axis=1)
    out = dict(run=run, t=js['tr'][sel] - t0, c=np.array(cs), rate=np.array(rate),
               c_topic=(ct['tr'] - t0, ct['data']) if ct else None,
               status=(st['tr'] - t0, st['code']) if st else None,
               tu=ur['t'] - (t0 - (js['tr'][0] - bags.to_run_clock(run, bags.load(run)) if False else 0)),
               dist=d, return_gap=float(d[-1]), travel=float(d.max()),
               qd_max=float(np.degrees(np.abs(js['qd']).max())),
               wrist_qd_max=float(np.degrees(np.abs(js['qd'][:, 3:]).max())))
    # map UR_PATH t to the bag clock for plotting distance against the same time axis
    out['tu'] = ur['t'] if off0 is not None else ur['t']
    if ct:
        ci = np.interp(js['tr'][sel], ct['tr'], ct['data'])
        out['c_check'] = float(np.nanmedian(np.abs(ci - out['c']) / out['c']))
    return out


def main():
    style()
    real = runs.find_runs('V9b/Singularity/*/SingularityInput_Replay*')
    mock = runs.find_runs('V9b/SingularityMock/*')
    res = [analyse(r) for r in real]
    mres = [analyse(r) for r in mock]
    guard = lambda r: bool(r.settings.get('TOUCH_SINGULARITY_GUARD'))
    s0 = real[0].settings
    L = ['# S02 Results: singularity guard', '', 'Generated by `analysis.py`. c = condition number of the 6×6 tool0 '
         'Jacobian recomputed from `/joint_states` with the run\'s kinematics; dc/dt = what the commanded twist '
         'would do to c. Distances from `UR_PATH.csv` (tool0, whole recording).', '',
         f"Thresholds (META): guard slow {s0.get('TOUCH_SINGULARITY_SLOW')}, guard stop {s0.get('TOUCH_SINGULARITY_STOP')}; "
         f"Servo slowdown {s0.get('SERVO_SINGULARITY_SLOWDOWN')}, stop {s0.get('SERVO_SINGULARITY_STOP')} with the "
         f"guard off (raised to {s0.get('SERVO_SINGULARITY_SLOWDOWN_GUARDED')}/{s0.get('SERVO_SINGULARITY_STOP_GUARDED')} "
         'with it on).', '',
         '| Run | guard | kinematics | peak c | c topic vs recomputed (median rel. diff) | time c > 60 (s) | '
         'Servo halt (s) | max joint speed (°/s) | travel (mm) | return gap (mm) | commanded dc/dt while c > 50: median / p90 (1/s) |',
         '|---|---|---|---|---|---|---|---|---|---|---|']
    for r in res + mres:
        run = r['run']
        dt = np.diff(r['t'], prepend=r['t'][0])
        halt = float(np.sum(np.diff(r['status'][0], prepend=r['status'][0][0])[r['status'][1] == 2])) if r['status'] else np.nan
        hi = r['c'] > 50
        mr = r['rate'][hi & np.isfinite(r['rate'])]
        L.append(f"| {run.key} | {'on' if guard(run) else 'off'} | {run.kinematics[0]} | {r['c'].max():.1f} | "
                 f"{('%.3f' % r['c_check']) if 'c_check' in r else 'not published'} | {np.sum(dt[r['c'] > 60]):.1f} | {halt:.1f} | {r['qd_max']:.1f} | "
                 f"{r['travel']:.1f} | {r['return_gap']:.1f} | "
                 f"{(np.median(mr) if len(mr) else np.nan):.1f} / {(np.percentile(mr, 90) if len(mr) else np.nan):.1f} |")
    on = [r for r in res if guard(r['run'])]; off = [r for r in res if not guard(r['run'])]
    L += ['', f"**Real arm:** guard on returns within {min(r['return_gap'] for r in on):.1f}–"
          f"{max(r['return_gap'] for r in on):.1f} mm (peak c {min(r['c'].max() for r in on):.1f}–"
          f"{max(r['c'].max() for r in on):.1f}); guard off ends {min(r['return_gap'] for r in off):.1f}–"
          f"{max(r['return_gap'] for r in off):.1f} mm from its start (peak c {min(r['c'].max() for r in off):.1f}–"
          f"{max(r['c'].max() for r in off):.1f}), {len(off)} of {len(off)} replays.", '',
          '## Prior claims checked', '',
          '- "guard on: peak c 60.3–60.4, return within 0.5–0.6 mm; off: c ≈ 204, stuck 171.5–171.7 mm": see the table.',
          '- "the mock guard-off run escaped": see the GuardOff_mock row.', '', '## Figures', '']

    fig, (a1, a2) = plt.subplots(2, 1, figsize=(FULL * 0.85, 3.6), sharex=True)
    for r in res:
        col = ON if guard(r['run']) else OFF
        a1.plot(r['t'], r['c'], color=col, lw=0.9, alpha=0.8)
        a2.plot(r['tu'], r['dist'], color=col, lw=0.9, alpha=0.8)
        if r['status'] is not None and not guard(r['run']):
            ts, code = r['status']
            h = np.where(code == 2)[0]
            if len(h):
                a1.axvspan(ts[h[0]], ts[h[-1]], color=OFF, alpha=0.06, lw=0)
    for y, lab in ((60, 'Guard stop (60)'), (200, 'Servo halt (200)')):
        a1.axhline(y, color=INK2, ls='--', lw=0.7); a1.text(1, y * 1.08, lab, fontsize=8, color=INK2)
    a1.text(20, 110, 'Servo halted (guard off)', fontsize=8, color=OFF)
    a1.set_yscale('log'); a1.set_ylabel('Condition number $c$')
    a2.set_ylabel('Flange distance\nfrom start (mm)'); a2.set_xlabel('Time (s)')
    for r in on[:1] + off[:1]:
        a2.annotate(f"{r['return_gap']:.1f} mm", (r['tu'][-1], r['dist'][-1]), xytext=(-40, 6),
                    textcoords='offset points', fontsize=8, color=ON if guard(r['run']) else OFF)
    a1.legend(handles=[plt.Line2D([], [], color=ON, label='Guard on (3 replays)'),
                       plt.Line2D([], [], color=OFF, label='Guard off (3 replays)')], loc='lower right', bbox_to_anchor=(1.0, 1.0), ncol=2)
    L.append(f"- `figures/{os.path.basename(save(fig, HERE, 'guard_timeseries'))}`")

    fig, ax = plt.subplots(figsize=(FULL * 0.6, 2.8))
    for r in res + mres:
        is_mock = r['run'] in mock
        col = ON if guard(r['run']) else OFF
        d = np.interp(r['t'], r['tu'], r['dist'])
        ax.plot(r['c'], d, color=col, lw=0.8 if not is_mock else 0.9, ls=':' if is_mock else '-', alpha=0.85)
        ax.plot(r['c'][-1], d[-1], 'o', color=col, ms=4, mfc='white' if is_mock else col)
    ax.set_xscale('log'); ax.set_xlabel('Condition number $c$'); ax.set_ylabel('Flange distance from start (mm)')
    ax.set_title('Dotted: mock arm; dot: end', fontsize=8)
    L.append(f"- `figures/{os.path.basename(save(fig, HERE, 'guard_phase_portrait'))}`")
    open(os.path.join(HERE, 'RESULTS.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
