"""S02 Singularity guard on the real arm (data/recordings/V9b/Singularity) and on the mock (data/recordings/V9b/SingularityMock).

Per run: condition number recomputed from /joint_states (kinematics from META) and compared with the published
topic; Servo status events; the rate at which the *commanded* twist would change c (dc/dt = (J^-T grad_q c) . twist)
- the guard's claim is that this never stays positive near its stop threshold; tool0 path from UR_PATH.csv
(start -> furthest -> end). Writes figures/ and RESULTS.md.
"""
