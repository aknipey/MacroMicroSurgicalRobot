#!/usr/bin/env python3
"""S01 Joint-speed amplification towards the wrist singularity (report 4.2.1).

Along the real-arm guard-off stroke (V9b/Singularity/GuardOff, replay 1), the Jacobian of every tenth /joint_states
sample (calibrated kinematics); the largest joint speed per unit tool twist is 1 / s_min(J). Reported relative to the
stroke's start pose, at the samples where the condition number c first crosses 30, 60, 100 and 200.
Writes RESULTS.md and figures/singularity_amplification.
"""
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(os.path.dirname(HERE)))  # thesis/results
from common import bags, kin, runs  # noqa: E402
from common.style import FULL, INK2, save, style  # noqa: E402
import matplotlib.pyplot as plt  # noqa: E402


def amplification():
    r = runs.Run(os.path.join(runs.LOGS, 'V9b/Singularity/GuardOff/SingularityInput_Replay1'))
    K = kin.load(r.kinematics[0] or 'calibrated')
    js = bags.load(r, ['/joint_states'])['/joint_states']
    q = js['q'][::10]
    sv = np.array([np.linalg.svd(kin.jacobian(K, x), compute_uv=False) for x in q])
    c = sv[:, 0] / sv[:, -1]
    amp = (1 / sv[:, -1]) / (1 / sv[0, -1])
    out = [('start', c[0], 1.0)]
    for thr in (30, 60, 100, 200):
        i = np.where(c >= thr)[0]
        if len(i):
            out.append((f'c ≥ {thr} (first)', c[i[0]], amp[i[0]]))
    return r.key, out, (c, amp)


def main():
    style()
    key, amp, (cs, amps) = amplification()
    L = ['# S01 Results: joint-speed amplification towards the wrist singularity', '', 'Generated by `analysis.py`.', '',
         f'Run: {key}, calibrated kinematics.', '',
         '| Pose | condition number c | largest joint speed per unit tool twist, relative to the start |', '|---|---|---|']
    L += [f'| {n} | {c:.1f} | {a:.1f}× |' for n, c, a in amp]
    fig, ax = plt.subplots(figsize=(FULL * 0.5, 2.3))
    ax.plot(cs, amps, '.', ms=2, color='#0072B2')
    for thr, lab in ((60, 'Guard stop'), (200, 'Servo halt')):
        ax.axvline(thr, color=INK2, lw=0.7, ls=':')
        ax.text(thr * 0.96, max(amps) * 0.97, lab, fontsize=8, color=INK2, ha='right', va='top')
    ax.set_xscale('log'); ax.set_xlabel('Condition number $c$')
    ax.set_ylabel('Joint speed per unit tool\nmotion (relative to start)')
    L += ['', '## Figures', '',
          f"- `figures/{os.path.basename(save(fig, HERE, 'singularity_amplification'))}`: largest joint speed per unit "
          "tool twist (1/s_min, relative to the start pose) against c along the guard-off stroke (report appendix A)",
          '', '## Prior claims checked', '',
          '- "at c = 100 a joint moves ~50× faster than the tool suggests": see the table.']
    open(os.path.join(HERE, 'RESULTS.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
