#!/usr/bin/env python3
"""Write data/RECORDINGS.md (one row per recording) and data/MANIFEST.sha256 (checksum of every file).

    python3 data/make_index.py              # index + manifest (the manifest hashes ~17 GB: about a minute)
    python3 data/make_index.py --no-hash    # index only

Every column comes from the run's own META.yaml / REPLAY.yaml (read through thesis/results/common/runs.py) or from
data/used_by.json (written by thesis/results/run_all.py). Nothing is typed in except NOTES below, which explains the
folder names that look like junk but are part of the results.
"""
import collections
import hashlib
import json
import os
import sys
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'thesis', 'results'))
from common import runs  # noqa: E402

REC = os.path.join(HERE, 'recordings')
SESSIONS = {   # top folder -> what it is (session letters as used in the report)
    'V1': 'Stack V1, single moves and the first benchmarks',
    'V2': 'Stack V2',
    'V3': 'Stack V3 (trajectory output); CyclingScaling is the emulator validation input',
    'V4': 'Stack V4, first velocity output (both benchmarks ended in a joint fault)',
    'V5': 'Stack V5',
    'V6': 'Stack V6, first RCM runs (fixed tip scale)',
    'V7': 'Stack V7, session A: first tracked RCM replays (nominal kinematics)',
    'V8': 'Stack V8, session B: calibrated kinematics',
    'V9': 'Stack V9, session B: position and trajectory output',
    'V9b': 'Stack V9b, session C: same-day output-mode benchmark, singularity guard, camera test, demo',
    'V9c': 'Stack V9c, session D: output mode x filter grid, RCM set, latch (tool line) test',
    'SIM_latency': 'Mock UR16e + arm emulator, latency variants',
    'Exchange': 'Quick-change coupling exchange sessions (tracker only), one folder per coupling version',
}
NOTES = {   # folders whose names look like junk but which the results use
    'V4/LongBenchmark_failed': 'ended in a joint fault; the fault is the result (L01, L04)',
    'V4/ShortBenchmark_failed': 'ended in a joint fault; the fault is the result (L04)',
    'V8/UNSAVED_2026-10-30_171830': 'live session the recorder saved under its default name; one of the stall-count runs (L10)',
    'V9b/PoseOffset_Camera2_FAILED_catchup': 'motion did not complete; kept to show the check rejects it (R04)',
    'V8/CalibratedKinematics/RCMOnlySimpleHolder_Replay1_WRONG_SCALE_1to1': 'replayed at the wrong scale; only its motor current is used (L11)',
    'V8/CalibratedKinematics/RCMOnlySimpleHolder_Replay2_WRONG_SCALE_1to1': 'replayed at the wrong scale; only its motor current is used (L11)',
    'V8/CalibratedKinematics/RCMOnlySimpleHolder_Replay3_WRONG_SCALE_1to1': 'replayed at the wrong scale; only its motor current is used (L11)',
    'V9c/Latch/B_tool11/FastCheckingRCMSimpleHolder_Replay2_WRONG_SCALE': 'did not run as recorded; excluded by R05\'s path check',
    'V9c/Latch/A_tool10_drift/FastCheckingRCMSimpleHolder_Replay1_NO_NDI': 'wand tracked in 79 % of the run; excluded by R05\'s visibility check',
}


def run_dirs():
    for d, subs, files in os.walk(REC):
        if 'META.yaml' in files:
            subs[:] = []
            yield os.path.relpath(d, REC)


def main():
    used = json.load(open(os.path.join(HERE, 'used_by.json')))
    by_run = collections.defaultdict(set)
    for folder, v in used.items():
        for r in v['runs']:
            by_run[r].add(folder.split('_')[0])
    keys = sorted(run_dirs())
    other = sorted(os.path.relpath(os.path.join(d, f), REC) for d, _, fs in os.walk(REC) for f in fs
                   if not any(os.path.join(d, f).startswith(os.path.join(REC, k) + os.sep) for k in keys))
    groups = collections.defaultdict(list)
    for k in keys:
        groups[k.split('/')[0]].append(k)
    L = ['# Recordings index', '',
         'Generated by `data/make_index.py` from each run\'s META.yaml / REPLAY.yaml and `data/used_by.json`. '
         'Do not edit by hand. Paths are relative to `data/recordings/`. **Used by** = the result folders in '
         '`thesis/results/` that read the recording (M = methods, L = latency, S = safety, R = RCM, T = tooling). '
         'Mode is the robot output mode read from the run\'s settings; scale is the stylus-to-robot motion scale.', '',
         f'{len(keys)} recordings, {sum(1 for k in keys if by_run.get(k))} read by at least one result.', '']
    for top in sorted(groups, key=lambda t: list(SESSIONS).index(t) if t in SESSIONS else 99):
        ks = groups[top]
        dates = sorted(runs.Run(os.path.join(REC, k)).date for k in ks)
        L += [f'## {top}', '', f'{SESSIONS.get(top, "")}. {len(ks)} recordings, {dates[0]} to {dates[-1]}.', '',
              '| Recording | date | mode | input | scale | tracker | bag | used by | note |',
              '|---|---|---|---|---|---|---|---|---|']
        for k in ks:
            r = runs.Run(os.path.join(REC, k))
            L.append(f"| `{k}` | {r.date} | {r.mode} | {r.trajectory}{' (replay)' if r.replay else ''} | "
                     f"{r.scale:g} | {'yes' if r.has('NDI_PATH.csv') else '–'} | {'yes' if r.has('rosbag') else '–'} | "
                     f"{', '.join(sorted(by_run.get(k, []))) or '–'} | {NOTES.get(k, '')} |")
        L.append('')
    L += ['## Other files', '', 'Recordings without a META.yaml (tracker-only exchange sessions, the demo\'s node logs) and '
          'lab notes. The REPLAYS_*.md notes were written during each session; their explanations are claims that the '
          'results tested, not results.', '']
    L += [f'- `{f}`' for f in other]
    open(os.path.join(HERE, 'RECORDINGS.md'), 'w').write('\n'.join(L) + '\n')
    print(f'RECORDINGS.md: {len(keys)} recordings')
    if '--no-hash' in sys.argv:
        return
    files = sorted(os.path.relpath(os.path.join(d, f), REC) for d, _, fs in os.walk(REC) for f in fs)

    def sha(f):
        h = hashlib.sha256()
        with open(os.path.join(REC, f), 'rb') as fh:
            for b in iter(lambda: fh.read(1 << 22), b''):
                h.update(b)
        return f'{h.hexdigest()}  {f}'
    with ThreadPoolExecutor(8) as ex:
        lines = list(ex.map(sha, files))
    open(os.path.join(HERE, 'MANIFEST.sha256'), 'w').write('\n'.join(lines) + '\n')
    print(f'MANIFEST.sha256: {len(files)} files')


if __name__ == '__main__':
    main()
